import type { SeriesDto } from '../../../src/api/types'
import { cover, daysAgo } from '../api'
import { catalogue, type CatalogueEntry } from '../shared'

function toSeries(entry: CatalogueEntry): SeriesDto {
  return {
    id: entry.id,
    title: entry.title,
    displayTitle: entry.title,
    sortTitle: entry.title.toLowerCase(),
    originalTitle: entry.nativeTitle,
    altTitles: [],
    status: entry.status,
    type: entry.type.toLowerCase(),
    overview: entry.synopsis,
    year: entry.year,
    genres: entry.genres,
    metadataTags: entry.tags,
    contentRating: 'safe',
    tagIds: [],
    monitored: true,
    monitorNewItems: 'All',
    archivedAt: null,
    archivedByUserId: null,
    rootFolderId: 1,
    folderName: entry.title,
    rootFolderPath: `/library/${entry.title}`,
    coverUrl: cover(entry.id),
    totalChapters: entry.chapters,
    totalVolumes: null,
    authorStory: entry.author,
    authorArt: entry.artist,
    publisher: null,
    rating: null,
    mangaBakaId: entry.mangaBakaId,
    aniListId: null,
    malId: null,
    kitsuId: null,
    links: [],
    numberingClash: null,
    added: daysAgo(30 + entry.id * 9),
    wantedChapterCount: entry.chapters,
    chapterFileCount: entry.chapters,
    removedChapterCount: 0,
    readFileCleanup: 'Default',
    readFileCleanupActive: false,
    knownChapterCount: entry.chapters,
    queuedCount: 0,
    downloadingCount: 0,
    hasAnime: false,
    animeName: null,
    animeStart: null,
    animeEnd: null,
    readChapterCount: entry.read,
    sourceMatchPending: false,
    importLinkPending: false,
    incognito: 'Off',
    notificationMode: 'Default',
    upgradeProfileId: null,
    lastUpgradeScan: null,
    pendingProposalId: null,
    lockedFields: [],
  } satisfies SeriesDto
}

/** The shared catalogue as the `/series` list returns it, enough for the command palette to search. */
export const paletteSeries: SeriesDto[] = catalogue.map(toSeries)
