// Antigravity reads neither .claude/rules nor nested AGENTS.md files, so this writes one glob rule
// per source into .agents/rules/: each Claude rule (globs from its `paths` frontmatter) and each
// nested AGENTS.md (globs for its whole folder).
//
//   node scripts/agents/sync-antigravity-rules.mjs          rewrite .agents/rules/
//   node scripts/agents/sync-antigravity-rules.mjs --check  exit 1 when it is out of date (CI)
//
// Antigravity truncates a rule past 24,000 bytes, so only sources under INLINE_LIMIT are inlined;
// larger ones get a pointer the agent follows with its own file tools.

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../../', import.meta.url))
const rulesDir = join(root, '.claude/rules')
const outDir = join(root, '.agents/rules')
const MARKER = 'Generated by scripts/agents/sync-antigravity-rules.mjs'
const INLINE_LIMIT = 20_000
const check = process.argv[2] === '--check'

const read = path => readFileSync(path, 'utf8').replace(/\r\n/g, '\n')

function frontmatterPaths(text, file) {
  const match = text.match(/^---\n([\s\S]*?)\n---\n/)
  if (!match) throw new Error(`${file} has no frontmatter`)
  const paths = []
  let inPaths = false
  for (const line of match[1].split('\n')) {
    if (/^paths:\s*$/.test(line)) { inPaths = true; continue }
    if (inPaths && /^\s+-\s+/.test(line)) {
      paths.push(line.replace(/^\s+-\s+/, '').trim().replace(/^["']|["']$/g, ''))
    } else if (inPaths && line.trim()) {
      inPaths = false
    }
  }
  if (!paths.length) throw new Error(`${file} has no paths in its frontmatter`)
  return paths
}

function wrapper({ source, globs, description, size }) {
  const quote = s => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
  const lines = [
    '---',
    'trigger: glob',
    `globs: ${quote(globs.join(', '))}`,
    `description: ${quote(description)}`,
    '---',
    '',
    `<!-- ${MARKER} from ${source}. Do not edit. -->`,
    '',
    `Before editing a file that matches this rule's globs, read \`${source}\` from the repository root in full. It holds the gotchas for this area.`,
  ]
  if (size <= INLINE_LIMIT) lines.push('', `@[${source}](../../${source})`)
  return lines.join('\n') + '\n'
}

const wanted = new Map()

for (const file of readdirSync(rulesDir).filter(f => f.endsWith('.md')).sort()) {
  const source = `.claude/rules/${file}`
  const text = read(join(rulesDir, file))
  const heading = text.match(/^# (.+)$/m)?.[1] ?? basename(file, '.md')
  wanted.set(file, wrapper({ source, globs: frontmatterPaths(text, source), description: heading, size: Buffer.byteLength(text) }))
}

const nested = execFileSync('git', ['ls-files', '--', '*/AGENTS.md'], { cwd: root, encoding: 'utf8' })
  .split('\n').filter(Boolean).filter(p => p.includes('/')).sort()
for (const source of nested) {
  const folder = dirname(source)
  const name = `folder-${folder.replace(/[^A-Za-z0-9]+/g, '-').toLowerCase()}.md`
  const size = Buffer.byteLength(read(join(root, source)))
  wanted.set(name, wrapper({ source, globs: [`${folder}/**`], description: `Notes for work under ${folder}/`, size }))
}

const existing = existsSync(outDir)
  ? readdirSync(outDir).filter(f => f.endsWith('.md') && read(join(outDir, f)).includes(MARKER))
  : []
const stale = existing.filter(f => !wanted.has(f))
const changed = [...wanted].filter(([f, body]) => !existsSync(join(outDir, f)) || read(join(outDir, f)) !== body).map(([f]) => f)

if (check) {
  if (stale.length || changed.length) {
    console.error(`.agents/rules is out of date (${[...changed, ...stale].join(', ')}). Run node scripts/agents/sync-antigravity-rules.mjs and commit the result.`)
    process.exit(1)
  }
  console.log(`.agents/rules matches its ${wanted.size} sources.`)
  process.exit(0)
}

mkdirSync(outDir, { recursive: true })
for (const f of stale) unlinkSync(join(outDir, f))
for (const f of changed) writeFileSync(join(outDir, f), wanted.get(f))
console.log(`Wrote ${changed.length}, removed ${stale.length}, ${wanted.size} rules in .agents/rules.`)
